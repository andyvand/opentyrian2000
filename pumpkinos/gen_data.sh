#!/bin/sh
# OpenTyrian 2000 PumpkinOS port: generate the resource descriptions for the
# bundled Tyrian 2000 data files.
#
# usage: gen_data.sh <data dir> <output dir>
#
# Writes <output dir>/data.rcp (pilrc DATA statements, one 'tdat' resource
# per data file) and <output dir>/data_index.inc (the C table mapping file
# names to resource ids, included by pumpkin_app.c).

set -e

if [ $# -ne 2 ]; then
  echo "usage: $0 <data dir> <output dir>" >&2
  exit 1
fi

datadir=$1
outdir=$2

case "$datadir" in
  /*) ;;
  *) datadir="$(pwd)/$datadir" ;;
esac

if [ ! -f "$datadir/tyrian1.lvl" ]; then
  echo "$0: $datadir does not look like a Tyrian 2000 data directory (tyrian1.lvl missing)" >&2
  exit 1
fi

mkdir -p "$outdir"

rcp="$outdir/data.rcp.tmp"
inc="$outdir/data_index.inc.tmp"

printf '/* generated by gen_data.sh from %s - do not edit */\n\n' "$datadir" > "$rcp"
printf '/* generated by gen_data.sh from %s - do not edit */\n' "$datadir" > "$inc"

id=1000
# sort for a reproducible numbering; names are matched case-insensitively
# at run time
ls "$datadir" | LC_ALL=C sort | while IFS= read -r name; do
  path="$datadir/$name"
  [ -f "$path" ] || continue
  case "$name" in
    .*) continue ;;
  esac
  # escape backslashes and double quotes for the rcp and C string literals
  esc=$(printf '%s' "$name" | sed 's/\\/\\\\/g; s/"/\\"/g')
  escpath=$(printf '%s' "$path" | sed 's/\\/\\\\/g; s/"/\\"/g')
  printf 'DATA "tdat" ID %d "%s"\n' "$id" "$escpath" >> "$rcp"
  printf '\t{ "%s", %d },\n' "$esc" "$id" >> "$inc"
  id=$((id + 1))
done

mv "$rcp" "$outdir/data.rcp"
mv "$inc" "$outdir/data_index.inc"

count=$(grep -c '^DATA' "$outdir/data.rcp")
echo "gen_data.sh: $count data files from $datadir"
